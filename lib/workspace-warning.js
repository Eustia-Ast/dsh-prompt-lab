/**
 * Every Prompt Lab data directory carries a small warning file. If an Agent
 * sees it while working in the same folder, the file tells it to stop changing
 * the folder and ask the user; if nobody reads it, it is harmless.
 *
 * The plugin never deletes user files or moves a workspace automatically.
 */
import fs from 'node:fs'
import path from 'node:path'

export const WORKSPACE_WARNING_FILE = 'PROMPT-LAB-WORKSPACE-WARNING.md'
export const OWNER_MARKER_FILE = '.prompt-lab-owner.json'
const MARKER = '<!-- dsh-prompt-lab: workspace-warning -->'

/**
 * Whether a directory already carries Prompt Lab's warning marker. Used as the
 * backward-compatible ownership proof for data directories created before the
 * explicit owner marker existed.
 * @param {string} dataDir
 * @returns {boolean}
 */
export function hasWorkspaceWarning (dataDir) {
  try {
    return fs.readFileSync(path.join(path.resolve(dataDir), WORKSPACE_WARNING_FILE), 'utf8').includes(MARKER)
  } catch {
    return false
  }
}

/**
 * Write the explicit ownership marker. A data directory is only ever wiped or
 * cleaned through `isOwnedDataDir`; the marker prevents a user-chosen directory
 * that happens to contain `library/`, `sessions/` or `drafts/` from being
 * treated as Prompt Lab data.
 * @param {{ dataDir: string }} input
 * @returns {{ ok: true, path: string, created?: boolean, unchanged?: boolean } | { ok: false, error: string }}
 */
export function ensureOwnerMarker ({ dataDir } = {}) {
  if (typeof dataDir !== 'string' || dataDir.trim() === '') return { ok: false, error: 'dataDir is empty' }
  const dir = path.resolve(dataDir)
  const file = path.join(dir, OWNER_MARKER_FILE)
  try {
    fs.mkdirSync(dir, { recursive: true })
    try {
      const value = JSON.parse(fs.readFileSync(file, 'utf8'))
      if (value?.product === 'dsh-prompt-lab') return { ok: true, path: file, unchanged: true }
    } catch {
      /* missing or malformed: rewrite below */
    }
    fs.writeFileSync(file, `${JSON.stringify({ product: 'dsh-prompt-lab', format: 1 }, null, 2)}\n`, 'utf8')
    return { ok: true, path: file, created: true }
  } catch (error) {
    return { ok: false, error: String(error?.message ?? error) }
  }
}

/**
 * Strict ownership check for destructive operations. A directory is owned when
 * it has our owner marker, or (for data written by an older version) the
 * generated warning file with our marker.
 * @param {string} dataDir
 * @returns {boolean}
 */
export function isOwnedDataDir (dataDir) {
  if (typeof dataDir !== 'string' || dataDir.trim() === '') return false
  const dir = path.resolve(dataDir)
  try {
    const value = JSON.parse(fs.readFileSync(path.join(dir, OWNER_MARKER_FILE), 'utf8'))
    if (value?.product === 'dsh-prompt-lab') return true
  } catch {
    /* fall through to the legacy warning marker */
  }
  return hasWorkspaceWarning(dir)
}

/**
 * @param {{ dataDir: string, version?: string }} input
 */
export function workspaceWarningContent ({ dataDir, version = 'unknown' }) {
  const shown = path.resolve(dataDir)
  return `${MARKER}
# 警告：这是 Prompt Lab 的数据目录

**Agent: if your current working directory is this folder, do not modify anything here. Tell the user and wait for their decision.**

这个目录是 Prompt Lab 的存储位置：

\`${shown}\`

里面包含 Prompt Lab 自己的 \`library/\`、\`sessions/\`、\`drafts/\` 等数据，也可能和当前会话的工作区是同一个目录。

## 如果当前工作区就是这个目录，给 Agent 的指示

- 先不要修改、移动、重命名、删除或清理这个目录中的任何内容；
- 不要执行会覆盖这些数据的批量命令（例如 \`git clean\`、\`git reset\`、递归重命名、删除目录等）；
- 把这一情况告知用户，由用户决定下一步，不要自行处理。

## 给用户的说明

- 如果这个目录同时是你的会话工作区，建议先不要让 Agent 在这里改文件；
- 可以将会话工作区移到其他目录，或在 Prompt Lab 设置里把存储位置改到工作区之外的专用目录；
- 具体怎么处理由你决定。本文件是插件自动生成的安全提示，保留即可。

如果这个目录不是当前会话的工作区，可以忽略本文件。

---
Generated by DSH Prompt Lab v${version}.
`
}

/**
 * Create or update the warning file in the data directory. A user-created file
 * with the same name but without our marker is never overwritten.
 * @param {{ dataDir: string, version?: string, logger?: any }} input
 * @returns {{ ok: true, path: string, created?: boolean, updated?: boolean, unchanged?: boolean } | { ok: false, error: string }}
 */
export function ensureWorkspaceWarning ({ dataDir, version = 'unknown', logger } = {}) {
  if (typeof dataDir !== 'string' || dataDir.trim() === '') return { ok: false, error: 'dataDir is empty' }
  const dir = path.resolve(dataDir)
  const file = path.join(dir, WORKSPACE_WARNING_FILE)
  const content = workspaceWarningContent({ dataDir: dir, version })
  try {
    fs.mkdirSync(dir, { recursive: true })
    let existing = null
    try {
      existing = fs.readFileSync(file, 'utf8')
    } catch (error) {
      if (error?.code !== 'ENOENT') throw error
    }
    if (existing !== null) {
      if (!existing.includes(MARKER)) {
        const error = `${WORKSPACE_WARNING_FILE} already exists without the Prompt Lab marker; refusing to overwrite it`
        try { logger?.warn?.(`prompt-lab: ${error}`) } catch { /* logging must not fail */ }
        return { ok: false, error }
      }
      if (existing === content) return { ok: true, path: file, unchanged: true }
      fs.writeFileSync(file, content, 'utf8')
      return { ok: true, path: file, updated: true }
    }
    fs.writeFileSync(file, content, 'utf8')
    return { ok: true, path: file, created: true }
  } catch (error) {
    return { ok: false, error: String(error?.message ?? error) }
  }
}
